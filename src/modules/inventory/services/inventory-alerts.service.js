// Alertas de Inventario (puntos 5 y 8): reutiliza el motor de alertas
// genérico de core/alerts (el mismo que ya usan Tesorería y Fiscal) —
// solo se agregan las funciones propias de qué condiciones detectar.
const { Prisma } = require('@prisma/client');
const prisma = require('../../../core/database/prisma');
const coreAlertsService = require('../../../core/alerts/alerts.service');
const { detectDueSoon, severityForDueSoon } = require('../../../core/alerts/alerts.rules');
const purchaseOrdersService = require('./purchase-orders.service');
const { calculateSuggestedReorderQuantity } = require('./purchase-orders.rules');

const { Decimal } = Prisma;

// Punto 5: escanea el stock de cada almacén contra su mínimo
// (StockLevel.minStock, o si no está fijado, Product.minStock),
// levanta una alerta LOW_STOCK y agrupa los productos bajo el mínimo
// por almacén+proveedor preferido para generar UNA orden de compra
// borrador por grupo — nunca duplica una orden automática ya abierta
// para ese mismo almacén+proveedor.
async function scanLowStock(companyId, userId) {
  const rule = await prisma.alertRule.findFirst({ where: { companyId, type: 'LOW_STOCK', isActive: true } });
  if (!rule) return { alertsCreated: [], purchaseOrdersGenerated: [] };

  const stockLevels = await prisma.stockLevel.findMany({
    where: { companyId },
    include: { variant: { include: { product: true } }, warehouse: true },
  });

  const alertsCreated = [];
  const groups = new Map();

  for (const level of stockLevels) {
    const threshold = level.minStock ?? level.variant.product.minStock;
    if (threshold == null) continue;
    if (new Decimal(level.quantityOnHand).greaterThanOrEqualTo(threshold)) continue;

    const alert = await coreAlertsService.createAlertIfNotExists({
      companyId,
      ruleId: rule.id,
      type: 'LOW_STOCK',
      severity: 'WARNING',
      message: `El producto "${level.variant.product.name}" (${level.variant.sku}) está bajo el mínimo en "${level.warehouse.name}" (${new Decimal(
        level.quantityOnHand
      ).toFixed(4)} de ${new Decimal(threshold).toFixed(4)}).`,
      entityType: 'StockLevel',
      entityId: level.id,
    });
    if (alert) alertsCreated.push(alert);

    const maxStock = level.maxStock ?? level.variant.product.maxStock;
    const suggestedQty = calculateSuggestedReorderQuantity(level.quantityOnHand, threshold, maxStock);
    if (suggestedQty.isZero()) continue;

    const vendorId = level.variant.product.preferredVendorId || null;
    const key = `${level.warehouseId}::${vendorId || 'none'}`;
    const group = groups.get(key) || { warehouseId: level.warehouseId, vendorId, lines: [] };
    group.lines.push({ variantId: level.variantId, quantityOrdered: suggestedQty.toFixed(4) });
    groups.set(key, group);
  }

  const purchaseOrdersGenerated = [];
  for (const group of groups.values()) {
    const existingOpenOrder = await prisma.purchaseOrder.findFirst({
      where: {
        companyId,
        warehouseId: group.warehouseId,
        vendorId: group.vendorId,
        isAutoGenerated: true,
        status: { in: ['DRAFT', 'SUBMITTED', 'PARTIALLY_RECEIVED'] },
      },
    });
    if (existingOpenOrder) continue;

    const order = await purchaseOrdersService.createPurchaseOrder(companyId, userId, {
      vendorId: group.vendorId,
      warehouseId: group.warehouseId,
      orderDate: new Date(),
      isAutoGenerated: true,
      notes: 'Generada automáticamente: uno o más productos bajaron de su stock mínimo.',
      lines: group.lines,
    });
    purchaseOrdersGenerated.push(order);
  }

  return { alertsCreated, purchaseOrdersGenerated };
}

// Punto 8: lotes con stock restante (suma de remainingQuantity en sus
// capas) cuya fecha de vencimiento está a `daysBefore` días o menos —
// mismas funciones puras de vencimiento que ya usan Tesorería/Fiscal.
async function scanExpiringLots(companyId) {
  const rule = await prisma.alertRule.findFirst({ where: { companyId, type: 'PRODUCT_EXPIRING_SOON', isActive: true } });
  if (!rule) return [];
  const daysBefore = rule.parameters?.daysBefore ?? 15;
  const today = new Date();

  const lots = await prisma.inventoryLot.findMany({
    where: { companyId, expirationDate: { not: null } },
    include: { variant: { include: { product: true } } },
  });

  const createdAlerts = [];
  for (const lot of lots) {
    if (!detectDueSoon(lot.expirationDate, today, daysBefore)) continue;

    const entryMovements = await prisma.inventoryMovement.findMany({
      where: { lotId: lot.id },
      select: { costLayersCreated: { select: { remainingQuantity: true } } },
    });
    const remaining = entryMovements
      .flatMap((m) => m.costLayersCreated)
      .reduce((sum, layer) => sum.plus(layer.remainingQuantity), new Decimal(0));
    if (remaining.lessThanOrEqualTo(0)) continue;

    const alert = await coreAlertsService.createAlertIfNotExists({
      companyId,
      ruleId: rule.id,
      type: 'PRODUCT_EXPIRING_SOON',
      severity: severityForDueSoon(lot.expirationDate, today),
      message: `El lote "${lot.lotNumber}" de "${lot.variant.product.name}" (${remaining.toFixed(4)} unidades) vence el ${lot.expirationDate
        .toISOString()
        .slice(0, 10)}.`,
      entityType: 'InventoryLot',
      entityId: lot.id,
    });
    if (alert) createdAlerts.push(alert);
  }

  return createdAlerts;
}

async function runInventoryAlertsScan(companyId, userId) {
  const [lowStock, expiringLots] = await Promise.all([scanLowStock(companyId, userId), scanExpiringLots(companyId)]);
  return {
    lowStock: lowStock.alertsCreated,
    purchaseOrdersGenerated: lowStock.purchaseOrdersGenerated,
    expiringLots,
    totalAlertsCreated: lowStock.alertsCreated.length + expiringLots.length,
  };
}

module.exports = { scanLowStock, scanExpiringLots, runInventoryAlertsScan };
