// Reabastecimiento Automático y Ciclo de Compra (punto 5). Recibir
// mercancía contra una orden reutiliza inventory-movements.createEntry
// (nunca postea un asiento aparte) — la orden de compra en sí no tiene
// efecto contable, solo documenta la intención de comprar.
const { Prisma } = require('@prisma/client');
const prisma = require('../../../core/database/prisma');
const AppError = require('../../../core/utils/AppError');
const auditService = require('../../../core/audit/audit.service');
const inventoryMovementsService = require('./inventory-movements.service');
const { withTransaction } = require('../../../core/database/unit-of-work');
const { calculateReceiptDiscrepancy, determinePurchaseOrderStatus } = require('./purchase-orders.rules');

const { Decimal } = Prisma;

async function createPurchaseOrder(companyId, userId, data) {
  const warehouse = await prisma.warehouse.findFirst({ where: { id: data.warehouseId, companyId, isActive: true } });
  if (!warehouse) {
    throw new AppError('El almacén indicado no existe o está inactivo.', 404, 'WAREHOUSE_NOT_FOUND');
  }
  if (data.vendorId) {
    const vendor = await prisma.vendor.findFirst({ where: { id: data.vendorId, companyId } });
    if (!vendor) {
      throw new AppError('El proveedor indicado no existe.', 404, 'VENDOR_NOT_FOUND');
    }
  }
  if (!Array.isArray(data.lines) || data.lines.length === 0) {
    throw new AppError('La orden de compra necesita al menos una línea.', 400, 'PURCHASE_ORDER_LINES_REQUIRED');
  }
  for (const line of data.lines) {
    const variant = await prisma.productVariant.findFirst({ where: { id: line.variantId, product: { companyId } } });
    if (!variant) {
      throw new AppError('Una de las variantes indicadas no existe.', 404, 'PRODUCT_VARIANT_NOT_FOUND');
    }
  }

  return prisma.$transaction(async (tx) => {
    const order = await tx.purchaseOrder.create({
      data: {
        companyId,
        vendorId: data.vendorId || null,
        warehouseId: data.warehouseId,
        orderDate: data.orderDate,
        expectedDate: data.expectedDate || null,
        isAutoGenerated: data.isAutoGenerated || false,
        notes: data.notes || null,
        createdByUserId: userId,
        lines: {
          create: data.lines.map((line) => ({
            variantId: line.variantId,
            quantityOrdered: line.quantityOrdered,
            unitCost: line.unitCost ?? null,
          })),
        },
      },
      include: { lines: true },
    });

    await auditService.log(
      { companyId, userId, action: 'purchase_order.created', entityType: 'PurchaseOrder', entityId: order.id, oldValue: null, newValue: order },
      tx
    );

    return order;
  });
}

async function submitPurchaseOrder(companyId, userId, id) {
  const order = await prisma.purchaseOrder.findFirst({ where: { id, companyId } });
  if (!order) {
    throw new AppError('La orden de compra indicada no existe.', 404, 'PURCHASE_ORDER_NOT_FOUND');
  }
  if (order.status !== 'DRAFT') {
    throw new AppError('Solo se pueden enviar órdenes en borrador.', 409, 'INVALID_STATUS');
  }

  return prisma.$transaction(async (tx) => {
    const updated = await tx.purchaseOrder.update({ where: { id }, data: { status: 'SUBMITTED' } });
    await auditService.log(
      {
        companyId,
        userId,
        action: 'purchase_order.submitted',
        entityType: 'PurchaseOrder',
        entityId: id,
        oldValue: { status: 'DRAFT' },
        newValue: { status: 'SUBMITTED' },
      },
      tx
    );
    return updated;
  });
}

// Recibir mercancía: cada línea recibida genera su propia entrada de
// inventario (misma cuenta contrapartida para toda la recepción, igual
// simplificación que ya usa AR/AP con una sola cuenta por factura).
// Se calcula la discrepancia contra lo pedido, pero no bloquea nada —
// solo se informa (una recepción parcial, o incluso una sobre-recepción,
// es normal en la práctica). Fase 4: TODO esto — cada entrada de
// inventario, el acumulado de quantityReceived/receivedCostTotal de
// cada línea y el nuevo estado de la orden — ahora queda en UNA sola
// transacción (antes createEntry abría su propia transacción por línea
// y el resto de las escrituras quedaban sueltas: un fallo a mitad de
// camino podía dejar inventario movido sin que la orden lo reflejara).
async function receivePurchaseOrder(companyId, userId, id, { date, counterpartyAccountId, receipts }) {
  const order = await prisma.purchaseOrder.findFirst({ where: { id, companyId }, include: { lines: true } });
  if (!order) {
    throw new AppError('La orden de compra indicada no existe.', 404, 'PURCHASE_ORDER_NOT_FOUND');
  }
  if (!['SUBMITTED', 'PARTIALLY_RECEIVED'].includes(order.status)) {
    throw new AppError('Solo se puede recibir mercancía de órdenes enviadas o parcialmente recibidas.', 409, 'INVALID_STATUS');
  }
  if (!Array.isArray(receipts) || receipts.length === 0) {
    throw new AppError('Debes indicar al menos una línea recibida.', 400, 'RECEIPTS_REQUIRED');
  }

  const linesById = new Map(order.lines.map((line) => [line.id, line]));
  for (const receipt of receipts) {
    const line = linesById.get(receipt.lineId);
    if (!line) {
      throw new AppError('Una de las líneas indicadas no pertenece a esta orden.', 404, 'PURCHASE_ORDER_LINE_NOT_FOUND');
    }
    const unitCost = receipt.unitCost ?? line.unitCost;
    if (unitCost == null) {
      throw new AppError('Debes indicar el costo unitario de recepción (la línea no tiene uno estimado).', 400, 'UNIT_COST_REQUIRED');
    }
  }

  return withTransaction(async (tx) => {
    const discrepancies = [];

    for (const receipt of receipts) {
      const line = linesById.get(receipt.lineId);
      const unitCost = receipt.unitCost ?? line.unitCost;

      const movement = await inventoryMovementsService.createEntry(
        companyId,
        userId,
        {
          variantId: line.variantId,
          warehouseId: order.warehouseId,
          type: 'PURCHASE_ENTRY',
          quantity: receipt.quantityReceived,
          unitCost,
          date,
          counterpartyAccountId,
          referenceType: 'PurchaseOrder',
          referenceId: order.id,
          purchaseOrderLineId: line.id,
          lotNumber: receipt.lotNumber,
          expirationDate: receipt.expirationDate,
          notes: `Recepción de orden de compra #${order.id}`,
        },
        tx
      );

      const newQuantityReceived = new Decimal(line.quantityReceived).plus(receipt.quantityReceived);
      const newReceivedCostTotal = new Decimal(line.receivedCostTotal).plus(movement.totalCost);
      await tx.purchaseOrderLine.update({
        where: { id: line.id },
        data: { quantityReceived: newQuantityReceived, receivedCostTotal: newReceivedCostTotal },
      });
      linesById.set(line.id, { ...line, quantityReceived: newQuantityReceived, receivedCostTotal: newReceivedCostTotal });

      const { discrepancy, hasDiscrepancy } = calculateReceiptDiscrepancy(line.quantityOrdered, newQuantityReceived);
      discrepancies.push({ lineId: line.id, variantId: line.variantId, discrepancy: discrepancy.toFixed(4), hasDiscrepancy });
    }

    const newStatus = determinePurchaseOrderStatus([...linesById.values()], order.status);
    const updated = await tx.purchaseOrder.update({
      where: { id },
      data: { status: newStatus },
      include: { lines: true },
    });

    await auditService.log(
      {
        companyId,
        userId,
        action: 'purchase_order.received',
        entityType: 'PurchaseOrder',
        entityId: id,
        oldValue: { status: order.status },
        newValue: { status: newStatus },
      },
      tx
    );

    return { order: updated, discrepancies };
  });
}

async function cancelPurchaseOrder(companyId, userId, id) {
  const order = await prisma.purchaseOrder.findFirst({ where: { id, companyId } });
  if (!order) {
    throw new AppError('La orden de compra indicada no existe.', 404, 'PURCHASE_ORDER_NOT_FOUND');
  }
  if (!['DRAFT', 'SUBMITTED'].includes(order.status)) {
    throw new AppError('Solo se pueden cancelar órdenes en borrador o enviadas sin recepción.', 409, 'INVALID_STATUS');
  }

  return prisma.$transaction(async (tx) => {
    const updated = await tx.purchaseOrder.update({ where: { id }, data: { status: 'CANCELLED' } });
    await auditService.log(
      {
        companyId,
        userId,
        action: 'purchase_order.cancelled',
        entityType: 'PurchaseOrder',
        entityId: id,
        oldValue: { status: order.status },
        newValue: { status: 'CANCELLED' },
      },
      tx
    );
    return updated;
  });
}

async function getPurchaseOrder(companyId, id) {
  const order = await prisma.purchaseOrder.findFirst({
    where: { id, companyId },
    include: { lines: true, vendor: true, warehouse: true, createdByUser: { select: { id: true, name: true } } },
  });
  if (!order) {
    throw new AppError('La orden de compra indicada no existe.', 404, 'PURCHASE_ORDER_NOT_FOUND');
  }
  return order;
}

async function listPurchaseOrders(companyId, { status, warehouseId, vendorId } = {}) {
  return prisma.purchaseOrder.findMany({
    where: { companyId, status: status || undefined, warehouseId: warehouseId || undefined, vendorId: vendorId || undefined },
    include: { lines: true, vendor: true, warehouse: true },
    orderBy: { createdAt: 'desc' },
  });
}

module.exports = {
  createPurchaseOrder,
  submitPurchaseOrder,
  receivePurchaseOrder,
  cancelPurchaseOrder,
  getPurchaseOrder,
  listPurchaseOrders,
};
